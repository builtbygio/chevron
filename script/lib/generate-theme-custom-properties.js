'use strict';

/**
 * Regenerate packages/<theme>/styles/custom-properties.less for every theme,
 * publishing the variables that theme overrides as CSS custom properties.
 *
 * See docs/reference/theme-custom-properties.md.
 *
 * Usage: node script/lib/generate-theme-custom-properties.js [--check]
 */

const fs = require('fs');
const path = require('path');

const ROOT = path.resolve(__dirname, '..', '..');
const PACKAGES = path.join(ROOT, 'packages');

function declaredIn(file) {
  const names = [];
  const src = fs.readFileSync(file, 'utf8');
  for (const m of src.matchAll(/^\s*@([a-zA-Z][a-zA-Z0-9-]*)\s*:/gm)) {
    names.push(m[1]);
  }
  return names;
}

function themeDirs() {
  return fs
    .readdirSync(PACKAGES)
    .filter(entry => {
      const manifest = path.join(PACKAGES, entry, 'package.json');
      if (!fs.existsSync(manifest)) return false;
      let theme;
      try {
        ({ theme } = JSON.parse(fs.readFileSync(manifest, 'utf8')));
      } catch (error) {
        return false;
      }
      return theme === 'ui' || theme === 'syntax';
    })
    .sort();
}

function themeKind(theme) {
  return JSON.parse(
    fs.readFileSync(path.join(PACKAGES, theme, 'package.json'), 'utf8')
  ).theme;
}

// A base variable is published only if some theme redefines it.
function overriddenNames() {
  const base = {
    ui: declaredIn(path.join(ROOT, 'static', 'variables', 'ui-variables.less')),
    syntax: declaredIn(
      path.join(ROOT, 'static', 'variables', 'syntax-variables.less')
    )
  };
  const known = new Set([...base.ui, ...base.syntax]);
  const overridden = new Set();
  for (const theme of themeDirs()) {
    const dir = path.join(PACKAGES, theme, 'styles');
    if (!fs.existsSync(dir)) continue;
    for (const entry of fs.readdirSync(dir)) {
      if (!entry.endsWith('.less') || entry === 'custom-properties.less') {
        continue;
      }
      for (const name of declaredIn(path.join(dir, entry))) {
        if (known.has(name)) overridden.add(name);
      }
    }
  }
  return {
    ui: base.ui.filter(n => overridden.has(n)),
    syntax: base.syntax.filter(n => overridden.has(n))
  };
}

// The lightness band a colour must sit in to stay legible on an overlay,
// derived from the UI theme alone so consumers compile once.
const OVERLAY_BAND = `
// 40 is the minimum lightness separation from the overlay background.
.chevron-overlay-contrast-band() when (lightness(@overlay-background-color) < 50) {
  --overlay-contrast-l-min: unit(lightness(@overlay-background-color) + 40);
  --overlay-contrast-l-max: 100;
}
.chevron-overlay-contrast-band() when (lightness(@overlay-background-color) >= 50) {
  --overlay-contrast-l-min: 0;
  --overlay-contrast-l-max: unit(lightness(@overlay-background-color) - 40);
}

// +1 on a dark theme (lighten), -1 on a light one (darken): expresses at
// runtime the branch LESS's contrast() picked at build time.
.chevron-contrast-sign() when (lightness(@base-background-color) < 50) {
  --contrast-shift-sign: 1;
}
.chevron-contrast-sign() when (lightness(@base-background-color) >= 50) {
  --contrast-shift-sign: -1;
}
`;

// Syntax themes publish their own sign, so a mixed pair (dark UI, light
// syntax) still picks the right ink.
const SYNTAX_BAND = `
.chevron-syntax-contrast-sign() when (lightness(@syntax-background-color) < 50) {
  --syntax-contrast-shift-sign: 1;
}
.chevron-syntax-contrast-sign() when (lightness(@syntax-background-color) >= 50) {
  --syntax-contrast-shift-sign: -1;
}
`;

function render(kind, names) {
  const importName = kind === 'ui' ? 'ui-variables' : 'syntax-variables';
  return (
    `// GENERATED by script/lib/generate-theme-custom-properties.js -- do not edit.
//
// Publishes this theme's LESS variables as CSS custom properties on :root.
// Package stylesheets read var(--name) instead of @name, so they compile once
// instead of once per UI x syntax theme pair, and a theme switch is a
// stylesheet swap rather than a recompile.
//
// LESS resolves these in THIS theme's context, so each theme emits its own
// values under the same property names.

@import "${importName}";
${kind === 'ui' ? OVERLAY_BAND : SYNTAX_BAND}
:root {
` +
    names.map(n => `  --${n}: @${n};`).join('\n') +
    (kind === 'ui'
      ? '\n  .chevron-overlay-contrast-band();\n  .chevron-contrast-sign();'
      : '\n  .chevron-syntax-contrast-sign();') +
    '\n}\n'
  );
}

function main() {
  const check = process.argv.includes('--check');
  const names = overriddenNames();
  const stale = [];
  let written = 0;

  for (const theme of themeDirs()) {
    const dir = path.join(PACKAGES, theme, 'styles');
    if (!fs.existsSync(dir)) continue;
    const kind = themeKind(theme);
    const target = path.join(dir, 'custom-properties.less');
    const next = render(kind, names[kind]);
    const current = fs.existsSync(target)
      ? fs.readFileSync(target, 'utf8')
      : null;
    if (current === next) continue;
    if (check) {
      stale.push(path.relative(ROOT, target));
    } else {
      fs.writeFileSync(target, next);
      written++;
    }
  }

  if (check) {
    if (stale.length) {
      console.error(
        'custom-properties.less is stale in:\n  ' + stale.join('\n  ')
      );
      console.error('\nRun: node script/lib/generate-theme-custom-properties.js');
      process.exit(1);
    }
    console.log(
      `custom-properties.less up to date in ${themeDirs().length} themes ` +
        `(${names.ui.length} ui, ${names.syntax.length} syntax)`
    );
    return;
  }

  console.log(
    `regenerated ${written} of ${themeDirs().length} themes ` +
      `(${names.ui.length} ui, ${names.syntax.length} syntax)`
  );
}

main();
